export function t(key: string, paramsOrFallback?: Record<string, any> | string, params?: Record<string, any>): string {
  const lang = currentLang;
  let text = key;

  if (lang === 'en') {
    text = translations.en[key] || (typeof paramsOrFallback === 'string' ? paramsOrFallback : key);
  } else {
    text = translations.zh[key] || key;
  }

  const p = typeof paramsOrFallback === 'object' && paramsOrFallback !== null ? paramsOrFallback : params;
  if (p) {
    Object.keys(p).forEach((k) => {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(p[k]));
    });
  }

  return text;
}

interface I18nContextType {
  lang: Lang;
  setLang: (lang: Lang | ((prev: Lang) => Lang)) => void;
  t: typeof t;
}

const I18nContext = createContext<I18nContextType>({
  lang: 'zh',
  setLang: () => {},
  t,
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(getStoredLang);

  useEffect(() => {
    currentLang = lang;
    const handleStorage = (e: StorageEvent) => {
      if (e.key === STORAGE_KEY && (e.newValue === 'en' || e.newValue === 'zh')) {
        setLangState(e.newValue);
        currentLang = e.newValue;
      }
    };
    window.addEventListener('storage', handleStorage);
    return () => window.removeEventListener('storage', handleStorage);
  }, [lang]);

  const setLang = (next: Lang | ((prev: Lang) => Lang)) => {
    const nextVal = typeof next === 'function' ? next(lang) : next;
    setStoredLang(nextVal);
    setLangState(nextVal);
  };

  const translate = (key: string, paramsOrFallback?: Record<string, any> | string, params?: Record<string, any>) => {
    return t(key, paramsOrFallback, params);
  };

  return React.createElement(
    I18nContext.Provider,
    { value: { lang, setLang, t: translate } },
    children
  );
}

export function useI18n() {
  return useContext(I18nContext);
}
