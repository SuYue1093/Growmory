import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
const base = process.env.TEST_BASE_URL || 'http://127.0.0.1:5198';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
const errors = [];
page.on('pageerror', e => errors.push(e.message));
try {
  const current = await page.request.get(base + '/api/state').then(r => r.json());
  const reset = await page.request.put(base + '/api/state', { data: { revision: current.revision, data: { products: [], docs: [], releases: [], contents: [], tasks: [] } } });
  assert.ok(reset.ok());
  await page.goto(base + '/#page=operations&scope=all');
  mkdirSync('.screenshots', { recursive: true });
  await page.getByRole('navigation', {name:'运营平台'}).getByRole('button',{name:'Reddit',exact:true}).click();
  await page.getByRole('heading', { name: '还没有Reddit账号' }).waitFor();
  assert.equal(await page.getByRole('table').count(), 0);
  await page.screenshot({ path: '.screenshots/social-analytics-onboarding.png', fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: '添加账号', exact: true }).click();
  const form = page.locator('form');
  await form.getByLabel('平台', { exact: true }).selectOption('reddit');
  await form.getByLabel('账号名称').fill('QA Reddit');
  await form.getByLabel('账号主页链接').fill('https://www.reddit.com/user/growmory-qa');
  await form.getByRole('button', { name: '保存账号' }).click();
  await page.getByRole('status').filter({ hasText: '数据已保存' }).waitFor();
  await page.getByRole('heading', { name: '还没有内容数据' }).waitFor();
  await page.getByRole('button', { name: '也可以手动录入' }).click();
  await page.getByLabel('内容标题', { exact: true }).fill('Growmory 测试内容');
  await page.getByLabel('内容链接', { exact: true }).fill('https://www.reddit.com/r/test/comments/growmory-qa');
  await page.getByLabel('阅读 / 浏览', { exact: true }).fill('1250');
  await page.getByLabel('Reddit 分数', { exact: true }).fill('-2');
  await page.getByLabel('来源与口径说明').fill('QA：Post Insights 累计浏览，测试数据');
  await page.getByRole('button', { name: '保存快照' }).click();
  await page.getByRole('link', { name: 'Growmory 测试内容' }).waitFor();
  await page.getByRole('button', { name: 'MCP 采集', exact: true }).click();
  assert.equal(await page.getByLabel('Agent 采集指令').isVisible(), false);
  await page.getByText('查看完整指令', { exact: true }).click();
  assert.match(await page.getByLabel('Agent 采集指令').inputValue(), /get_social_analytics_context/);
  await page.getByText('查看完整指令', { exact: true }).click();
  await page.screenshot({ path: '.screenshots/social-analytics-collection.png', fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: '导入数据', exact: true }).click();
  await page.getByText('导入 Agent JSON 数据', { exact: true }).click();
  const context = await page.request.get(base + '/api/social-analytics').then(r => r.json());
  const old = context.snapshots[0];
  const { id, ...snapshot } = old;
  await page.getByLabel('回填 JSON', { exact: true }).fill(JSON.stringify({ snapshots: [{ ...snapshot, observedAt: '2026-11-08T10:00:00Z', periodEnd: '2026-11-08', metrics: { views: 1500 } }, ...[6, 8].map(day => ({ ...snapshot, kind: 'account', title: 'QA Reddit', url: context.accounts[0].url, observedAt: `2026-11-0${day}T10:00:00Z`, periodEnd: `2026-11-0${day}`, metrics: { followers: day === 8 ? 100 : 90 } }))] }));
  await page.getByRole('button', { name: '校验并入库' }).click();
  await page.locator('.social-content-table td').filter({ hasText: '1,500' }).first().waitFor();
  assert.equal(await page.getByRole('link', { name: 'Growmory 测试内容' }).count(), 1);
  await page.getByLabel('显示全部历史').check();
  assert.equal(await page.getByRole('link', { name: 'Growmory 测试内容' }).count(), 2);
  assert.equal(await page.locator('.social-account-summary > div').count(), 2);
  await page.getByLabel('显示全部历史').uncheck();
  assert.equal(await page.locator('.social-account-summary > div').count(), 1);
  mkdirSync('.screenshots', { recursive: true });
  await page.screenshot({ path: '.screenshots/social-analytics-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForFunction(() => getComputedStyle(document.querySelector('.sidebar')).visibility === 'hidden');
  await page.getByLabel('查看账号', { exact: true }).selectOption(context.accounts[0].id);
  await page.screenshot({ path: '.screenshots/social-analytics-mobile.png', fullPage: true, animations: 'disabled' });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.getByRole('button', { name: 'MCP 采集', exact: true }).click();
  await page.keyboard.press('Escape');
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  await page.getByRole('heading', { name: '产品数据总览' }).waitFor();
  assert.deepEqual(errors, []);
  console.log('PASS: tabs, account creation, manual snapshot, JSON import, latest/history, mobile overflow, App analytics');
} finally { await browser.close(); }
