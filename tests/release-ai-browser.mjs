import { chromium } from '@playwright/test';
import { spawn } from 'node:child_process';
import { mkdtempSync, rmSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import assert from 'node:assert/strict';
const dir = mkdtempSync(join(tmpdir(), 'release-ai-ui-'));
const server = spawn(process.execPath, ['server/index.mjs'], { env: { ...process.env, NODE_ENV: 'production', PORT: '5198', DB_PATH: join(dir, 'db.sqlite'), AI_API_KEY: '' }, stdio: 'pipe' });
let browser;
try {
  await new Promise((resolve, reject) => { const t = setTimeout(() => reject(Error('启动超时')), 10000); server.stdout.on('data', s => { if (String(s).includes('Growmory')) { clearTimeout(t); resolve(); } }); server.once('error', reject); });
  browser = await chromium.launch({ channel: 'chrome', headless: true });
  const context = await browser.newContext({ permissions: ['clipboard-read', 'clipboard-write'] });
  const page = await context.newPage(); const errors = []; page.on('pageerror', e => errors.push(e.message));
  const base = 'http://127.0.0.1:5198';
  const state = await page.request.get(base + '/api/state').then(r => r.json());
  const data = JSON.parse(readFileSync('tests/helpers/workspace.json'));
  const doc = data.docs[0]; doc.status = 'confirmed';
  data.releases = [{ id: 'r', productId: doc.productId, version: 'QA-AI', changes: '新增导出', languages: ['中文'], channels: ['X'], status: 'preparing', createdAt: new Date().toISOString(), notes: [], proposals: [{ docId: doc.id, before: doc.body, body: doc.body + '\n\n新增导出功能', reason: '测试文档批阅', applied: false }] }];
  assert.equal((await page.request.put(base + '/api/state', { data: { revision: state.revision, data } })).status(), 200);
  await page.goto(base);
  await page.locator('.resume-release').filter({ hasText: 'QA-AI' }).click();
  await page.getByRole('button', { name: /3\. 知识库与新建营销/ }).first().click();
  await page.getByRole('button', { name: '复制营销提示词', exact: true }).click();
  const prompt = await page.evaluate(() => navigator.clipboard.readText());
  assert.ok(prompt.includes('新增导出') && prompt.includes('X') && !prompt.includes('base64'));
  await page.getByRole('button', { name: /测试文档批阅/ }).click();
  await page.getByRole('button', { name: '全部接受', exact: true }).waitFor();
  const staged = await page.request.get(base + '/api/state').then(r => r.json());
  const pending = staged.data.docs.find(d => d.id === doc.id);
  assert.equal(pending.status, 'pending'); assert.equal(pending.reviewBase.body, doc.body);
  await page.getByRole('button', { name: '全部接受', exact: true }).click();
  await page.getByRole('button', { name: '保存资料', exact: true }).click();
  await page.getByRole('button', { name: '保存资料', exact: true }).waitFor({ state: 'hidden' });
  const final = await page.request.get(base + '/api/state').then(r => r.json());
  assert.equal(final.data.docs.find(d => d.id === doc.id).status, 'confirmed');
  assert.ok(final.data.docs.find(d => d.id === doc.id).body.includes('新增导出功能'));
  assert.equal(final.data.contents.length, data.contents.length);
  assert.deepEqual(errors, []);
  console.log('通过：营销提示词复制、文档跳转批阅、接受保存、保留历史，无站内营销调用。');
} finally { await browser?.close(); server.kill(); await new Promise(r => server.once('exit', r)); rmSync(dir, { recursive: true, force: true }); }
